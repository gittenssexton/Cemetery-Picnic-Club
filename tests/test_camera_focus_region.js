// node tests/test_camera_focus_region.js
'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const src=fs.readFileSync(path.join(__dirname,'../web/camera/focus-region.js'),'utf8');
const ctx={module:{exports:{}}};vm.runInNewContext(src,ctx);
const {VERSION,fromTap,resolve}=ctx.module.exports;
assert.equal(VERSION,'CPC_FOCUS_REGION_V1');
const stone={box:{x:.2,y:.1,w:.45,h:.7},persistent_lock_id:12};
const focus=fromTap(stone,.37,.43);
assert.ok(focus&&focus.u>.3&&focus.u<.5&&focus.v>.4&&focus.v<.5);
const roi=resolve(stone,focus);
assert.equal(roi.is_detail,true);
assert.ok(roi.x>=stone.box.x&&roi.x+roi.w<=stone.box.x+stone.box.w+.00001);
assert.ok(roi.y>=stone.box.y&&roi.y+roi.h<=stone.box.y+stone.box.h+.00001);
const moved={...stone,box:{...stone.box,x:.28,y:.16}};
const shifted=resolve(moved,focus);
assert.ok(Math.abs(shifted.x-roi.x-.08)<.00001);
assert.ok(Math.abs(shifted.y-roi.y-.06)<.00001);
assert.equal(resolve({...stone,persistent_lock_id:13},focus),null,'Do not transfer focus to a different monument');
assert.equal(fromTap(stone,.9,.9),null,'Do not accept tap outside the known stone');
assert.equal(resolve(stone,null).kind,'full_stone_region');
const tiny={box:{x:.2,y:.2,w:.09,h:.1},persistent_lock_id:2};
const tinyR=resolve(tiny,fromTap(tiny,.23,.24));
assert.ok(tinyR.w<=tiny.box.w&&tinyR.h<=tiny.box.h,'Tiny stone ROI must remain inside geometry');
const discovery=fs.readFileSync(path.join(__dirname,'../web/camera/discovery.js'),'utf8');
const html=fs.readFileSync(path.join(__dirname,'../web/camera/index.html'),'utf8');
assert.ok(discovery.includes('CPCFocusRegion?.resolve'));
assert.ok(discovery.includes('CPCFocusRegion?.fromTap'));
assert.ok(discovery.includes('focusMetrics?{box:roi}:candidate'));
assert.ok(discovery.includes("ctx.clip()"));
assert.ok(html.includes('focus-region.js'));
assert.ok(html.includes('id="liveFocusWhole"'));
new Function(discovery);new Function(html.slice(html.lastIndexOf('<script>\n')+9,html.lastIndexOf('</script>')));
console.log('Stone-relative contextual tap, movement, separation and full-stone recovery checks passed');
